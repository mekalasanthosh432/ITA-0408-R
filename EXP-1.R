# Numeric vector
num_vec <- c(10, 20, 30, 40, 50)

# Character vector
char_vec <- c("Apple", "Banana", "Mango", "Orange")

# Logical vector
logical_vec <- c(TRUE, FALSE, TRUE, TRUE, FALSE)

# Display type and content
print(num_vec)
print(typeof(num_vec))

print(char_vec)
print(typeof(char_vec))

print(logical_vec)
print(typeof(logical_vec))
